const expandGoldenRle = (encoded: string): string => {
  let expanded = "";
  let consumed = 0;
  for (const match of encoded.matchAll(/([A-Z])(\d+)/g)) {
    if (match.index !== consumed) throw new Error("Malformed golden replay RLE.");
    const code = match[1];
    const count = Number(match[2]);
    if (code === undefined || !Number.isSafeInteger(count) || count <= 0) {
      throw new Error("Malformed golden replay RLE run.");
    }
    expanded += (code === "N" ? "0" : code).repeat(count);
    consumed += match[0].length;
  }
  if (consumed !== encoded.length) throw new Error("Malformed golden replay RLE suffix.");
  return expanded;
};

const expandGoldenCampDsl = (encoded: string): string =>
  encoded.split(";").map((token) => {
    const alternating = /^P([AB])(\d+)$/.exec(token);
    if (alternating === null) return expandGoldenRle(token);
    const first = alternating[1];
    const runCount = Number(alternating[2]);
    if ((first !== "A" && first !== "B") || !Number.isSafeInteger(runCount) || runCount <= 0) {
      throw new Error("Malformed golden replay alternating run.");
    }
    let expanded = "";
    for (let run = 0; run < runCount; run += 1) {
      expanded += (run % 2 === 0 ? first : first === "A" ? "B" : "A").repeat(24);
    }
    return expanded;
  }).join("");

